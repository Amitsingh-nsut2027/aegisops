/* Run against the local bridge. Uses installed Chrome and a separate browser profile. */
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.WORKBENCH_URL || 'http://127.0.0.1:5173';
const output = path.resolve(__dirname, '../../docs/design/review');
const checks = [];
function pass(name) {checks.push(name);}
(async () => {
  const browser = await chromium.launch({channel:'chrome', headless:true});
  try {
    const context = await browser.newContext({viewport:{width:1280,height:960}, permissions:['clipboard-read','clipboard-write']});
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base);
    await page.locator('.event-row').first().waitFor();
    await page.evaluate(() => document.fonts.ready);
    assert.equal(await page.evaluate(() => document.fonts.check('13px "IBM Plex Mono"') && document.fonts.check('20px "Space Grotesk"')), true);
    assert.equal(await page.locator('.event-row').count(), 4);
    pass('Actual API records and locally bundled fonts loaded');
    await page.screenshot({path:path.join(output,'02-final-1280.png'),fullPage:true});
    const firstId = await page.locator('.event-row').first().getAttribute('data-event');
    await page.locator('.event-row').nth(1).click();
    assert.notEqual(await page.locator('.event-row.selected').getAttribute('data-event'), firstId);
    assert.match(await page.locator('.run-picker').innerText(), /No saved run/);
    pass('Incident selection changes inspector and accurately shows no-run state');
    await page.locator('.event-row').first().click();
    await page.getByRole('tab', {name:'Trace',exact:true}).click();
    assert.equal(await page.locator('.trace-list li').count(), 5);
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.getByRole('tab', {name:'Runbooks',exact:true}).getAttribute('aria-selected'),'true');
    assert.equal(await page.locator('.runbook').count(), 2);
    await page.screenshot({path:path.join(output,'03-runbooks-1280.png'),fullPage:true});
    pass('Tabs, keyboard tab navigation, recorded trace and source guidance work');
    await page.getByRole('tab', {name:'Evidence',exact:true}).click();
    await page.getByRole('button',{name:'Copy event ID',exact:true}).click();
    const copied = await page.evaluate(() => navigator.clipboard.readText());
    assert.equal(copied,firstId);
    await page.locator('[data-time]').first().click();
    assert.match(await page.locator('#toast').innerText(), /UTC/);
    pass('Copy uses the full ID and timestamps reveal exact UTC time');
    await page.keyboard.press('/');
    assert.equal(await page.locator('#incident-filter').evaluate(el=>el===document.activeElement), true);
    await page.locator('#incident-filter').fill('does-not-exist');
    assert.equal(await page.locator('.event-row').count(),0);
    await page.screenshot({path:path.join(output,'04-empty-filter.png'),fullPage:true});
    await page.getByRole('button',{name:'Clear filter'}).click();
    await page.keyboard.press('Escape');
    await page.locator('.page-heading h1').click();
    await page.keyboard.press('j');
    assert.equal(await page.locator('.event-row.selected').getAttribute('data-event'), await page.locator('.event-row').nth(1).getAttribute('data-event'));
    await page.keyboard.press('k');
    assert.equal(await page.locator('.event-row.selected').getAttribute('data-event'),firstId);
    pass('Page-scoped filter, deliberate empty state and j/k row navigation work');
    await page.getByRole('separator').focus();
    const before = Number(await page.getByRole('separator').getAttribute('aria-valuenow'));
    await page.keyboard.press('ArrowLeft');
    assert.equal(Number(await page.getByRole('separator').getAttribute('aria-valuenow')),before+16);
    await page.keyboard.press('Home');
    assert.equal(Number(await page.getByRole('separator').getAttribute('aria-valuenow')),456);
    const separatorBox = await page.getByRole('separator').boundingBox();
    await page.mouse.move(separatorBox.x+2,300);await page.mouse.down();await page.mouse.move(separatorBox.x-30,300);await page.mouse.up();
    assert.ok(Number(await page.getByRole('separator').getAttribute('aria-valuenow'))>456);
    await page.getByRole('separator').dblclick({position:{x:2,y:200}});
    pass('Inspector resizes by pointer/keyboard, resets and persists preference');
    await page.getByRole('button',{name:'Open command palette'}).click();
    await page.locator('#command-search').fill('show trace');
    await page.keyboard.press('Enter');
    assert.equal(await page.getByRole('tab',{name:'Trace',exact:true}).getAttribute('aria-selected'),'true');
    await page.getByRole('button',{name:'Open command palette'}).click();
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('button',{name:'Open command palette'}).evaluate(el=>el===document.activeElement),true);
    await page.keyboard.press('Meta+k');
    assert.equal(await page.locator('#palette').evaluate(el=>el.open),true);
    await page.screenshot({path:path.join(output,'05-command-palette.png'),fullPage:true});
    await page.keyboard.press('Escape');
    pass('Cmd+K, command execution, Escape and focus restoration work');
    // Browser state remains free of the API token; only a pane preference is stored.
    assert.equal(await page.evaluate(()=>Object.keys(localStorage).some(key=>/token|auth/i.test(key))),false);
    assert.equal(await page.evaluate(()=>Object.keys(sessionStorage).length),0);
    pass('No viewer credential in browser storage');
    for (const width of [1024,768,390]) {
      await page.setViewportSize({width,height:960});
      await page.reload();await page.locator('.event-row').first().waitFor();await page.evaluate(()=>document.fonts.ready);
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
      await page.screenshot({path:path.join(output,`06-inbox-${width}.png`),fullPage:true});
      await page.locator('.event-row').first().click();
      assert.equal(await page.locator('.inspector').isVisible(),true);
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
      await page.screenshot({path:path.join(output,`07-detail-${width}.png`),fullPage:true});
      await page.getByRole('button',{name:'← Inbox',exact:true}).click();
      assert.equal(await page.locator('.workspace').isVisible(),true);
    }
    pass('1280/1024/768/390 layouts and mobile list/detail/back navigation have no page overflow');
    const stateContext = await browser.newContext({viewport:{width:1280,height:960}});
    const states = await stateContext.newPage();
    await states.route('**/api/events?**',route=>route.fulfill({status:401,json:{detail:'Session expired'}}));
    await states.goto(base);await states.getByText('Session expired',{exact:true}).waitFor();
    assert.equal(await states.locator('.event-row').count(),0);
    await states.screenshot({path:path.join(output,'08-session-expired.png'),fullPage:true});
    await states.unroute('**/api/events?**');
    await states.route('**/api/events?**',route=>route.fulfill({status:200,json:{items:[],limit:25,offset:0,returned:0,has_more:false}}));
    await states.reload();await states.getByText('No saved incidents',{exact:true}).waitFor();
    await states.screenshot({path:path.join(output,'09-empty-journal.png'),fullPage:true});
    await states.unroute('**/api/events?**');
    await states.route('**/api/events?**',route=>route.fulfill({status:503,json:{detail:'Unavailable'}}));
    await states.reload();await states.getByText('API unavailable',{exact:true}).waitFor();
    await states.screenshot({path:path.join(output,'10-api-error.png'),fullPage:true});
    await states.unroute('**/api/events?**');
    await states.route('**/api/investigations?**',route=>route.fulfill({status:503,json:{detail:'Unavailable'}}));
    await states.reload();await states.getByText('History unavailable',{exact:true}).last().waitFor();
    assert.equal(await states.locator('.event-row').count(),4);
    await states.screenshot({path:path.join(output,'11-history-error.png'),fullPage:true});
    await states.unroute('**/api/investigations?**');
    await states.route('**/api/events?**',async route=>{await new Promise(resolve=>setTimeout(resolve,1200));await route.continue();});
    await states.reload();await states.locator('.table-skeleton').first().waitFor();
    await states.screenshot({path:path.join(output,'12-loading.png'),fullPage:true});
    await states.locator('.event-row').first().waitFor();
    await states.emulateMedia({reducedMotion:'reduce'});
    assert.equal(await states.locator('.refresh-button').evaluate(el=>getComputedStyle(el).transitionDuration),'0s');
    pass('Expired session, empty journal, API/history errors, loading and reduced-motion states verified');
    await states.unroute('**/api/events?**');
    const saved = await states.request.get(base + '/api/investigations?limit=1');
    const history = await saved.json();
    const fallback = structuredClone(history.items[0]);
    fallback.payload.analysis.used_fallback = true;
    fallback.payload.runbook_context = {status:'unavailable',matches:[],error:'runbook_library_unavailable'};
    fallback.payload.evidence_checks[1] = {...fallback.payload.evidence_checks[1],status:'unavailable',source:'not_connected',detail:'No collector is connected.'};
    await states.route('**/api/investigations?**',route=>route.fulfill({status:200,json:{items:[fallback],returned:1,has_more:false,limit:100,offset:0}}));
    await states.reload();await states.getByText('Deterministic fallback used. Provider output did not pass validation.',{exact:true}).waitFor();
    await states.screenshot({path:path.join(output,'14-provider-fallback.png'),fullPage:true});
    await states.getByRole('tab',{name:'Runbooks',exact:true}).click();await states.getByText('Guidance unavailable',{exact:true}).waitFor();
    await states.screenshot({path:path.join(output,'15-guidance-unavailable.png'),fullPage:true});
    pass('Provider fallback and unavailable guidance/evidence remain explicit in mocked saved-report states');

    assert.deepEqual(errors,[]);
    pass('No JavaScript runtime errors');
    fs.writeFileSync(path.join(output,'browser-checks.json'),JSON.stringify({checks,screenshots:fs.readdirSync(output).filter(name=>name.endsWith('.png')),testedAt:new Date().toISOString()},null,2));
    console.log(checks.map(check=>'PASS '+check).join('\n'));
    await stateContext.close();await context.close();
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
